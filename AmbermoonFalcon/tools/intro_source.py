#!/usr/bin/env python3
"""Makes assembler source from the code hunk of Ambermoon_intro or Fantasy_intro (needs capstone; only used once,
KERNEL/INTRO.S and KERNEL/FANTASY.S are the results with their changes). Code is found by following the branches from
the entry points, the rest is data.

    intro_source.py <Ambermoon_intro> <out.s>
    intro_source.py <Fantasy_intro> <out.s> fantasy
    intro_source.py <Ambermoon_extro> <out.s> extro
"""
import os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from hunks import deplode, hunks
from capstone import Cs, CS_ARCH_M68K, CS_MODE_M68K_030, CS_MODE_BIG_ENDIAN

MODE = sys.argv[3] if len(sys.argv) > 3 else 'intro'
FANTASY = MODE != 'intro'          # (imploded, pointers in the code hunk)
H = hunks(sys.argv[1])
if FANTASY:
    H = deplode(H)
code, rel = H[0]['data'], H[0]['relocs']
md = Cs(CS_ARCH_M68K, CS_MODE_M68K_030 + CS_MODE_BIG_ENDIAN)
ROOTS = [0, 0xfe, 0x114, 0x12c, 0x2522, 0x28de, 0x29ea]
LABEL = 'L%05x'
NAME = {i: 'Intro_h%d' % i for i in range(len(H))}
if MODE == 'fantasy':     # (the table of the pixel routines : $8c0)
    ROOTS = [0x110, 0xd88] + [rel[o][1] for o in range(0x8c0, 0x940, 4)]
    LABEL = 'F%05x'
    NAME = {i: 'Fant_h%d' % i for i in range(len(H))}
if MODE == 'extro':     # (the trap, the program in supervisor mode, the interrupt)
    ROOTS = [0, 0x108, 0x120, 0xf26]
    LABEL = 'E%05x'
    NAME = {i: 'Extro_h%d' % i for i in range(len(H))}
insn, todo, labels = {}, list(ROOTS), set(ROOTS)
while todo:
    p = todo.pop()
    while p < len(code) and p not in insn:
        i = next(md.disasm(code[p:p + 12], p, 1), None)
        if i is None:
            raise SystemExit('no instruction at %x' % p)
        insn[p] = i
        m, ops = i.mnemonic, i.op_str
        target = None
        if re.match(r'(b[a-z]{2}|db[a-z]+)(\.[bwl])?$', m):
            target = int(ops.rsplit('$', 1)[1], 16)
        elif m.startswith(('jsr', 'jmp')):
            for o in range(p, p + i.size - 3):
                if o in rel and rel[o][0] == 0:
                    target = rel[o][1]
        if target is not None:
            labels.add(target)
            todo.append(target)
        if m.startswith(('rts', 'rte', 'bra', 'jmp')):
            break
        p += i.size
# data labels : everything a relocation points to in the code hunk, and pc relative targets
for h in H:
    for t in h['relocs'].values():
        if t[0] == 0:
            labels.add(t[1])
for p, i in insn.items():
    for m in re.finditer(r'\$([0-9a-f]+)\(pc', i.op_str):
        labels.add(int(m.group(1), 16))

def expr(h, off):
    return (LABEL % off) if h == 0 else '%s+$%x' % (NAME[h], off)

def text(p, i):
    m, ops = i.mnemonic.strip(), i.op_str.strip().replace(', ', ',')
    m = re.sub(r'^(btst|bset|bclr|bchg|s[a-z]{1,2})\.[bl]$', lambda g: g.group(1), m)
    if m == 'sub':
        m = 'sub.l'
    if re.match(r'(b[a-z]{2}|db[a-z]+)(\.[bwl])?$', m):
        t = int(ops.rsplit('$', 1)[1], 16)
        ops = ops[:ops.rindex('$')] + LABEL % t
    else:
        ops = re.sub(r'\$([0-9a-f]+)\(pc', lambda g: LABEL % int(g.group(1), 16) + '(pc', ops)
        for o in sorted((o for o in range(p, p + i.size - 3) if o in rel), reverse=True):
            h, off = rel[o]
            raw = struct.unpack_from('>I', code, o)[0]
            n = 0
            def sub(g):
                nonlocal_hits.append(1)
                return ('#' if g.group(1) else '') + (expr(h, off) if g.group(1) else '(' + expr(h, off) + ').l')
            nonlocal_hits = []
            first = o - p == 2                  # the first operand of the instruction
            pat = r'(#)?\$%x(?:\.l)?(?![0-9a-f(])' % raw
            parts = re.split(r',(?![^(]*\))', ops)
            done = False
            order = range(len(parts)) if first else range(len(parts) - 1, -1, -1)
            for k in order:
                if re.search(pat, parts[k]):
                    parts[k] = re.sub(pat, sub, parts[k], count=1)
                    done = True
                    break
            if not done:
                raise SystemExit('reloc not found %x %s %s' % (p, m, ops))
            ops = ','.join(parts)
    return m, ops

out = ['; generated by intro_source.py', '\tSECTION\tIntro_code,code']
p = 0
while p < len(code):
    if p in labels:
        out.append(LABEL % p + ':')
    if p in insn:
        m, ops = text(p, insn[p])
        out.append('\t%s\t%s\t; %05x' % (m, ops, p))
        p += insn[p].size
    else:
        off = struct.unpack_from('>H', code, p)[0]
        if FANTASY and p in rel:
            out.append('\tdc.l\t%s\t; %05x' % (expr(*rel[p]), p))
            p += 4
            continue
        if p in rel or (p + 2 in rel and not FANTASY):
            raise SystemExit('reloc in data %x' % p)
        out.append('\tdc.w\t$%04x\t; %05x' % (off, p))
        p += 2
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(insn), 'instructions,', len(out), 'lines')
