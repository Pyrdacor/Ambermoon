def cap(s):
    words = s.lower().split(' ')
    words = [w.upper() if w in ('i', 'ii', 'iii', 'iv', 'v', 'pv', 'pm') else w for w in words]
    out = ' '.join(words)
    return out[0].upper() + out[1:]


def write(rel, text):
    p = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8-sig', newline='') as f:
        f.write(text)


def read(base, rel):
    with open(os.path.join(base, rel), encoding='utf-8-sig') as f:
        return f.read().strip()


def files(cat):
    d = os.path.join(REF_EN, cat)
    return sorted(f for f in os.listdir(d) if f.endswith('.txt'))


